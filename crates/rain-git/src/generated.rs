/// Generator annotations in Java/Kotlin code. A bare `@Generated` is left out: it is also put on
/// hand-written classes to keep them out of coverage.
static JVM_CODE: LazyLock<RegexSet> = LazyLock::new(|| {
    set(&[
        r"@(?:javax|jakarta)\.annotation(?:\.processing)?\.Generated\b",
        r#"@Generated\(\s*(?:value\s*=\s*)?\{?\s*""#,
    ])
});

fn set(patterns: &[&str]) -> RegexSet {
    RegexSet::new(patterns).expect("generated-file patterns compile")
}

fn is_word(s: &str) -> bool {
    !s.is_empty() && s.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

fn has_generated_suffix(file_name: &str, marker: &str) -> bool {
    file_name.rfind(marker).is_some_and(|at| is_word(&file_name[at + marker.len()..]))
}

/// Layer 1: whether the path alone marks the file as generated.
pub fn generated_path(path: &str) -> bool {
    let file_name = path.rsplit('/').next().unwrap_or(path);
    let lower = file_name.to_ascii_lowercase();
    EXACT_FILENAMES.contains(&file_name)
        || FILENAME_SUFFIXES.iter().any(|s| lower.ends_with(s))
        || has_generated_suffix(file_name, ".generated.")
        || has_generated_suffix(file_name, ".gen.")
        || (file_name.starts_with("mock_") && file_name.ends_with(".go"))
        || (path.contains("mocks/") && file_name.ends_with(".go"))
        || ROOT_PATH_PREFIXES.iter().any(|p| path.starts_with(p))
        || PATH_SEGMENTS.iter().any(|s| path.contains(s))
}

/// The header difit scans: the first [`HEADER_LINES`] lines of the first [`HEADER_BYTES`].
pub fn header_text(head: &[u8]) -> String {
    let head = &head[..head.len().min(HEADER_BYTES)];
    let text = String::from_utf8_lossy(head);
    let mut out = String::with_capacity(text.len());
    for (i, l) in text.split('\n').take(HEADER_LINES).enumerate() {
        if i > 0 {
            out.push('\n');
        }
        out.push_str(l);
    }
    out
}

const COMMENT_STARTS: [&str; 8] = ["//", "#", "/*", "*", "<!--", "--", ";", "'"];

/// Lines that may come before a file's header comment without ending it.
const PREAMBLES: [&str; 2] = ["<?php", "<?xml"];

/// The file's leading comment lines: those before its first line of code. A string or a later
/// comment saying "do not edit" is not a header.
fn leading_comments(header: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut close: Option<&str> = None;
    for line in header.lines() {
        let t = line.trim_start_matches('\u{feff}').trim();
        if let Some(end) = close {
            out.push(line);
            if t.contains(end) {
                close = None;
            }
            continue;
        }
        if t.is_empty() || PREAMBLES.iter().any(|p| t.starts_with(p)) {
            continue;
        }
        if !COMMENT_STARTS.iter().any(|s| t.starts_with(s)) {
            break;
        }
        out.push(line);
        for (open, end) in [("/*", "*/"), ("<!--", "-->")] {
            if t.starts_with(open) && !t[open.len()..].contains(end) {
                close = Some(end);
            }
        }
    }
    out
}

/// Layers 2 and 3 over an already-cut header ([`header_text`]).
pub fn generated_header(path: &str, header: &str) -> bool {
    let file_name = path.rsplit('/').next().unwrap_or(path);
    let lower = file_name.to_ascii_lowercase();
    if lower.ends_with(".md") || lower.ends_with(".markdown") {
        return false;
    }
    let comments = leading_comments(header);
    if comments.iter().any(|l| UNIVERSAL.is_match(l.trim_start_matches('\u{feff}'))) {
        return true;
    }
    let ext = path
        .rfind('.')
        .map(|at| &path[at..])
        .filter(|e| e.len() > 1 && e[1..].bytes().all(|b| b.is_ascii_alphanumeric()))
        .unwrap_or("");
    if matches!(ext, ".java" | ".kt") && JVM_CODE.is_match(header) {
        return true;
    }
    let comments = comments.join("\n");
    LANGUAGE
        .iter()
        .find(|(exts, _)| exts.contains(&ext))
        .is_some_and(|(_, set)| set.is_match(&comments))
}

/// Whether a file is generated, from its repo-relative path and the first bytes of its
/// content (`head` may be empty, which checks the path only).
pub fn generated(path: &str, head: &[u8]) -> bool {
    generated_path(path) || (!head.is_empty() && generated_header(path, &header_text(head)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn paths() {
        assert!(generated("src/Data/Foo.Designer.cs", b""));
        assert!(generated("app/package-lock.json", b""));
        assert!(generated("web/app.min.js", b""));
        assert!(generated("api/types.generated.ts", b""));
        assert!(generated("node_modules/x/index.js", b""));
        assert!(generated("src/gen/x.ts", b""));
        assert!(!generated("gen/x.ts", b""));
        assert!(!generated("src/Services/VoucherService.cs", b""));
        assert!(!generated("src/x.generated.d-ts", b""));
    }

    #[test]
    fn markers() {
        assert!(generated("Migrations/Snap.cs", b"// <auto-generated />\nusing System;\n"));
        assert!(generated("Migrations/X.cs", b"// <auto-generated>\r\n"));
        assert!(generated("x.go", b"// Code generated by tool. DO NOT EDIT.\r\npackage x\n"));
        assert!(generated("x.ts", b"/* Generated by orval */"));
        assert!(!generated("README.md", b"<!-- DO NOT EDIT -->"));
        assert!(!generated("src/a.cs", b"using System;\nclass A {}\n"));
        let late = format!("{}// <auto-generated />\n", "x\n".repeat(25));
        assert!(!generated("src/a.cs", late.as_bytes()));
    }

    #[test]
    fn markers_in_comments_still_count() {
        assert!(generated("x.go", b"// Code generated by sqlc. DO NOT EDIT.\npackage x\n"));
        assert!(generated("src/a.rs", b"// @generated by build.rs\nfn a() {}\n"));
        assert!(generated("src/a.ts", b"/**\n * @generated\n */\nexport {}\n"));
        assert!(generated("src/a.py", b"# DO NOT EDIT: written by codegen\n"));
        assert!(generated("src/A.vb", b"' <auto-generated/>\n"));
        assert!(generated("src/a.cs", "\u{feff}// <auto-generated/>\n".as_bytes()));
        assert!(generated("q.sql", b"-- Generated by sqlc\n"));
    }

    #[test]
    fn markers_outside_comments_do_not_count() {
        assert!(!generated("src/a.rs", b"const P: &str = \"Do not edit files.\";\n"));
        assert!(!generated("docs/agent.md", b"# Agents\n\nDo not edit the session file by hand.\n"));
        assert!(!generated("docs/notes.txt", b"Generated by hand, do not edit.\n"));
        assert!(!generated(
            "tools/cache.py",
            b"\"\"\"Reads the build cache.\n\nDo not edit the cache by hand; it is generated by `make`.\n\"\"\"\nimport os\n"
        ));
        let prompt = r#"//! The prompt a question becomes: a fixed preamble, where the review stands, the parts of the
//! Brief that touch the question, the anchored excerpt, the thread so far and the question.
//! Pure and deterministic; it only ever holds what the caller passes in.

use rain_core::BriefDoc;

pub const PREAMBLE: &str = "You are answering a code-review question inside Rain, a diff viewer. \
Answer in 150 words or fewer. Cite code as path:line. Do not edit files. \
If the answer is not in the excerpt, say so and name what you would read next.";
"#;
        assert!(!generated("crates/rain-ask/src/prompt.rs", prompt.as_bytes()));
    }

    #[test]
    fn a_marker_must_open_a_leading_comment() {
        assert!(!generated(
            "src/Api/AuthController.cs",
            b"// Session ids are generated by the server\nusing System;\n"
        ));
        assert!(!generated(
            "src/Session.cs",
            b"using System;\nclass Session {\n    /// Generated by the server on login.\n    string Id;\n}\n"
        ));
        assert!(!generated(
            "src/a.ts",
            b"import x from 'x';\n// DO NOT EDIT below without a review\n"
        ));
        assert!(!generated(
            "src/Foo.java",
            b"package a;\n@Generated\nclass Foo {}\n// NOTE: OpenAPI Generator would do this\n"
        ));
        assert!(generated(
            "src/Client.cs",
            b"//------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n//------\nusing System;\n"
        ));
        assert!(generated("src/a.ts", b"/*\n  Generated by orval\n*/\nexport {}\n"));
        assert!(generated("x.php", b"<?php\n/** @generated */\nclass A {}\n"));
        assert!(generated(
            "src/Api.java",
            b"package a;\n@javax.annotation.Generated(value = \"org.openapitools\")\nclass Api {}\n"
        ));
        assert!(generated("app/migrations/0002_x.py", b"# Generated by Django 4.2 on 2026-01-01\n"));
    }

    #[test]
    fn ordinary_sources_are_not_generated_by_name() {
        for path in [
            "web/src/app/payments.api.ts",
            "web/src/mocks/handlers.msw.ts",
            "pkg/url/query_string.go",
            "go.mod",
            "build/deploy.js",
            "out/notes.ts",
        ] {
            assert!(!generated(path, b""), "{path}");
        }
        assert!(generated(
            "x_string.go",
            b"// Code generated by \"stringer -type=X\"; DO NOT EDIT.\n"
        ));
    }
}
