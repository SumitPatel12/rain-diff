const PATH_SEGMENTS: [&str; 3] = ["/generated/", "/gen/", "/__generated__/"];

/// A generated-file marker opening a comment's text (`// Generated by x`, ` * @generated`), not one
/// mentioned mid-sentence (`// Session ids are generated by the server`).
static UNIVERSAL: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?ix)^\s*(?: //+!? | \#+!? | /\*+!? | \*+ | <!-- | --+ | ;+ | ' )?\s*(?:
            @generated\b
          | <auto-?generated\b
          | auto[-\ ]?generated\b
          | code\ generated\b
          | generated\ (?:code|file|by)\b
          | machine\ generated\b
          | do\ not\ (?:edit|modify)\b
          | this\ (?:file|code|class)\ (?:is|was)\ (?:automatically\ |auto[-\ ]?)?@?generated\b
          | this\ is\ an?\ (?:auto[-\ ]?)?generated\ file\b
          | created\ by\ .*\ -\ do\ not\ edit
        )",
    )
    .expect("generated-file marker compiles")
});

