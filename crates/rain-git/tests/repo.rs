#[test]
fn whitespace_only_changes_are_formatting_only() {
    let s = scratch("ws");
    let r = resolve(&s.0, &launch("HEAD~1", "HEAD", false)).unwrap();
    let files = diff(&s.0, 0, &r, &DiffOpts::default()).unwrap();
    let changed: Vec<&str> = files
        .iter()
        .filter(|f| f.additions + f.deletions > 0)
        .map(|f| f.path.as_str())
        .collect();
    let only = formatting_only(&s.0, &r, &changed).unwrap();
    assert_eq!(only.into_iter().collect::<Vec<_>>(), ["src/ws.cs"]);
    let opts = DiffOpts {
        ignore_whitespace: true,
        ..DiffOpts::default()
    };
    let ignoring = diff(&s.0, 0, &r, &opts).unwrap();
    assert!(ignoring.iter().all(|f| f.path != "src/ws.cs" || f.lines.is_empty()));

    for jobs in [1, 4] {
        let p = diff_patch(&s.0, 0, &r, &DiffOpts { jobs, ..opts }).unwrap();
        assert_eq!(p.formatting_only, ["src/ws.cs"], "jobs {jobs}");
        let ws = find(&p.files, "src/ws.cs");
        assert_eq!(
            (ws.status, ws.hunks.len()),
            (FileStatus::Modified, 0),
            "still listed so the tree can tag it"
        );
    }
    assert!(diff_patch(&s.0, 0, &r, &DiffOpts::default()).unwrap().formatting_only.is_empty());
}

