    let loaded = head_sha(&s.0).unwrap();
    assert_eq!(target_moved(&s.0, "HEAD", &loaded, &loaded).unwrap(), None);
    git(&s.0, &["commit", "-q", "--allow-empty", "-m", "a"]);
